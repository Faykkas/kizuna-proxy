/** Tri et recherche des articles (fonction pure, testée). */
export type ShopSort = "featured" | "priceAsc" | "priceDesc" | "newest";
export type ShopItem = { id: string; name: string | null; image_url: string; price_jpy: number; fee_jpy: number; sort_order: number; created_at: string };

export function filterAndSort<T extends ShopItem>(items: T[], query: string, sort: ShopSort): T[] {
  const q = query.trim().toLowerCase().normalize("NFKC");
  const words = q ? q.split(/\s+/) : [];
  const hit = (i: T) => {
    const name = (i.name ?? "").toLowerCase().normalize("NFKC");
    return words.every((w) => name.includes(w));
  };
  const total = (i: T) => i.price_jpy + i.fee_jpy;
  const list = items.filter(hit);
  const by: Record<ShopSort, (a: T, b: T) => number> = {
    featured: (a, b) => a.sort_order - b.sort_order,
    priceAsc: (a, b) => total(a) - total(b) || a.sort_order - b.sort_order,
    priceDesc: (a, b) => total(b) - total(a) || a.sort_order - b.sort_order,
    newest: (a, b) => b.created_at.localeCompare(a.created_at),
  };
  return [...list].sort(by[sort]);
}
