export const XMAS_COPY: Record<string, XmasCopy> = { en, fr, ja, es, it, de, ko, zh, pt, id, vi, nl };

export function xmasCopy(lang?: string): XmasCopy {
  return XMAS_COPY[lang || "en"] || XMAS_COPY.en;
}

/** Remplace {clé} par sa valeur. */
export function fillX(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

